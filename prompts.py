# Выбран по итогам сравнения (см. reports/day02_prompt_comparison.md)
BEST_VARIANT = "v4_combined"


def detect_language(text):
    """Грубо определяет язык: если кириллицы больше, чем латиницы, — русский."""
    cyrillic = sum("а" <= ch.lower() <= "я" or ch.lower() == "ё" for ch in text)
    latin = sum("a" <= ch.lower() <= "z" for ch in text)
    return "русский" if cyrillic >= latin else "английский"


def build_prompts(text, variant=BEST_VARIANT):
    """Возвращает (system_prompt, user_prompt) для выбранного варианта."""
    if variant not in PROMPT_VARIANTS:
        raise ValueError(f"Неизвестный вариант промпта: {variant}. Есть: {list(PROMPT_VARIANTS)}")
    prompt = PROMPT_VARIANTS[variant]
    # лишние параметры (language) str.format просто игнорирует в шаблонах, где их нет
    user = prompt["user"].format(text=text.strip(), language=detect_language(text), **LIMITS)
    return prompt["system"], user