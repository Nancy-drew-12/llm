"""Промпты пайплайна. Логики здесь нет, только тексты."""

SYSTEM_PROMPT = (
    "Ты — аккуратный ассистент по анализу текстов. "
    "Отвечай на том же языке, на котором написан текст пользователя. "
    "Не придумывай фактов, которых нет в тексте."
)

ANALYZE_PROMPT = """Проанализируй текст ниже и верни ответ строго в формате JSON без пояснений и без markdown.

Формат:
{{
  "summary": "краткое содержание в 1-2 предложениях",
  "key_points": ["мысль 1", "мысль 2", "мысль 3"],
  "response": "короткий полезный ответ автору текста (2-4 предложения)"
}}

Требования:
- в key_points ровно 3 пункта, каждый — одно короткое предложение;
- response должен помогать автору: ответить на вопрос, предложить следующий шаг или совет.

Текст:
\"\"\"
{text}
\"\"\"
"""


def build_analyze_prompt(text):
    return ANALYZE_PROMPT.format(text=text.strip())
